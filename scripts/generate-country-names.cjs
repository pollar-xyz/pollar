// Writes packages/core/src/lib/country-names.generated.ts: every ISO 3166-1
// alpha-2 region Node's Intl names, in English, Spanish and Portuguese.
// countryName() reads it on engines without Intl.DisplayNames (Hermes).
//
// Run with `node scripts/generate-country-names.cjs` after a Node upgrade
// changes a name; the output is formatted by prettier.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const LANGUAGES = ['en', 'es', 'pt'];
const names = Object.fromEntries(
  LANGUAGES.map((language) => [language, new Intl.DisplayNames([language], { type: 'region', fallback: 'none' })]),
);

const rows = [];
for (let a = 65; a <= 90; a++)
  for (let b = 65; b <= 90; b++) {
    const code = String.fromCharCode(a, b);
    const row = LANGUAGES.map((language) => names[language].of(code));
    if (row.every(Boolean)) rows.push(`  ${code}: ${JSON.stringify(row)},`);
  }

const out = path.resolve(__dirname, '../packages/core/src/lib/country-names.generated.ts');
fs.writeFileSync(
  out,
  [
    '// Generated by scripts/generate-country-names.cjs from Node ' + process.version + '. Do not edit.',
    '',
    '/** Region names by ISO 3166-1 alpha-2 code, as [en, es, pt]. */',
    'export const COUNTRY_NAMES: Readonly<Record<string, readonly [string, string, string]>> = {',
    ...rows,
    '};',
    '',
  ].join('\n'),
);
execFileSync(require.resolve('prettier/bin/prettier.cjs'), ['--write', out], { stdio: 'ignore' });
console.log(`wrote ${rows.length} regions to ${path.relative(process.cwd(), out)}`);
