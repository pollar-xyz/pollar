#!/usr/bin/env node
'use strict';

// Writes src/exports.generated.ts: every name each @pollar entry point exports
// in this checkout, read from the built .d.ts files (run `npm run build` first).
// The CLI flags an import of a name that is not on this list.
//
// `--check` exits 1 when the committed file differs from what the build exports,
// so a release that adds or removes an export cannot ship a stale list.

const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const prettier = require('prettier');

const PACKAGES = path.join(__dirname, '..', '..');
const OUTPUT = path.join(__dirname, '..', 'src', 'exports.generated.ts');

const ENTRY_POINTS = {
  '@pollar/core': 'core/dist/index.d.mts',
  '@pollar/core/ramps': 'core/dist/ramps/index.d.mts',
  '@pollar/react': 'react/dist/index.d.mts',
  '@pollar/react-native': 'react-native/dist/index.d.mts',
  '@pollar/stellar-wallets-kit-adapter': 'stellar-wallets-kit-adapter/dist/index.d.mts',
  '@pollar/solana-wallet-standard-adapter': 'solana-wallet-standard-adapter/dist/index.d.mts',
};

function exportedNames(file) {
  const program = ts.createProgram([file], { noEmit: true, skipLibCheck: true, types: [] });
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(file);
  if (!source) throw new Error(`cannot read ${file}; build the packages first`);
  const moduleSymbol = checker.getSymbolAtLocation(source);
  if (!moduleSymbol) throw new Error(`${file} has no exports`);
  return checker
    .getExportsOfModule(moduleSymbol)
    .map((symbol) => symbol.getName())
    .filter((name) => name !== 'default')
    .sort();
}

async function main() {
  const entries = Object.entries(ENTRY_POINTS).map(([specifier, relative]) => [
    specifier,
    exportedNames(path.join(PACKAGES, relative)),
  ]);
  const body = entries.map(([specifier, names]) => `  ${JSON.stringify(specifier)}: ${JSON.stringify(names)},`).join('\n');
  const source = [
    '// Generated by scripts/generate-exports.cjs from the built packages. Do not edit.',
    '',
    'export const TARGET_EXPORTS: Record<string, readonly string[]> = {',
    body,
    '};',
    '',
  ].join('\n');
  const config = await prettier.resolveConfig(OUTPUT);
  const formatted = await prettier.format(source, { ...config, filepath: OUTPUT });

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== formatted) {
      console.error(
        'packages/migrate/src/exports.generated.ts is stale: run `node packages/migrate/scripts/generate-exports.cjs`',
      );
      process.exit(1);
    }
    console.log('migrate exports list is current');
    return;
  }
  fs.writeFileSync(OUTPUT, formatted);
  console.log(`wrote ${path.relative(process.cwd(), OUTPUT)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
